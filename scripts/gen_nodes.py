"""Generate deploy/kwok/nodes.yaml from data/venue.json (R2).

One KWOK fake Node per talk slot x room (20) and per break x table (14), as in
docs/AFFINITY.md. Seats are the extended resource `affinity.dev/seats`.
Talk Node names are `<slot>-<room>`, the same as Karthik's `talks.node`.

    python scripts/gen_nodes.py      # writes deploy/kwok/nodes.yaml
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENUE = ROOT / "data" / "venue.json"
OUT = ROOT / "deploy" / "kwok" / "nodes.yaml"
SEATS = "affinity.dev/seats"


def node(name: str, kind: str, slot: str, seats: int, caps: list[str], extra: dict) -> dict:
    labels = {
        "type": "kwok",
        "kubernetes.io/hostname": name,
        "affinity.dev/kind": kind,
        "affinity.dev/slot": slot,
        **extra,
        **{f"affinity.dev/{code}": "true" for code in caps},
    }
    resources = {"cpu": "32", "memory": "256Gi", "pods": "1000", SEATS: str(seats)}
    return {
        "apiVersion": "v1",
        "kind": "Node",
        "metadata": {
            "name": name,
            "annotations": {"kwok.x-k8s.io/node": "fake", "node.alpha.kubernetes.io/ttl": "0"},
            "labels": labels,
        },
        "spec": {"taints": [{"key": "kwok.x-k8s.io/node", "value": "fake", "effect": "NoSchedule"}]},
        "status": {"allocatable": resources, "capacity": resources},
    }


def build(venue: dict) -> list[dict]:
    nodes = []
    for slot in venue["slots"]:
        for room in venue["rooms"]:
            nodes.append(node(f"{slot}-{room['id']}", "talk", slot, room["seats"], room["caps"],
                              {"affinity.dev/room": room["id"]}))
    for brk in venue["breaks"]:
        for table in venue["tables"]:
            nodes.append(node(f"{brk}-{table['id']}", "table", brk, table["seats"], table["caps"],
                              {"affinity.dev/table": table["id"]}))
    return nodes


def to_yaml(nodes: list[dict]) -> str:
    """Multi-document YAML via JSON (valid YAML), so no YAML library is needed."""
    header = "# Generated by scripts/gen_nodes.py from data/venue.json. Do not edit by hand.\n"
    return header + "".join(f"---\n{json.dumps(n, indent=2)}\n" for n in nodes)


if __name__ == "__main__":
    nodes = build(json.loads(VENUE.read_text()))
    OUT.write_text(to_yaml(nodes))
    print(f"Wrote {len(nodes)} Nodes to {OUT}")
